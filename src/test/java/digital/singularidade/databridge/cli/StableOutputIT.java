package digital.singularidade.databridge.cli;

import digital.singularidade.databridge.support.FbFixture;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

import java.io.IOException;
import java.io.OutputStream;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

class StableOutputIT {

    private static FbFixture fx;

    @BeforeAll
    static void start() { fx = new FbFixture(); }

    @AfterAll
    static void stop() { fx.close(); }

    private static int extractAll(Path out) {
        return new CommandLine(new Main()).setErr(new PrintWriter(OutputStream.nullOutputStream()))
            .execute("extract-all", "--jdbc-url", fx.jdbcUrl(), "--out", out.toString(),
                "--include-triggers", "--stable", "-q");
    }

    private static List<Path> files(Path root) throws IOException {
        try (Stream<Path> s = Files.walk(root)) {
            return s.filter(Files::isRegularFile).map(root::relativize).sorted().toList();
        }
    }

    @Test
    void should_write_byte_identical_files_on_every_run(@TempDir Path tmp) throws Exception {
        assertThat(extractAll(tmp.resolve("a"))).isZero();
        Thread.sleep(1100);
        assertThat(extractAll(tmp.resolve("b"))).isZero();
        List<Path> a = files(tmp.resolve("a"));
        assertThat(a).isEqualTo(files(tmp.resolve("b"))).contains(Path.of("_index.json"));
        for (Path rel : a) {
            assertThat(Files.readString(tmp.resolve("b").resolve(rel)))
                .as(rel.toString()).isEqualTo(Files.readString(tmp.resolve("a").resolve(rel)));
        }
    }

    @Test
    void should_leave_out_volatile_fields_and_generated_names(@TempDir Path tmp) throws Exception {
        assertThat(extractAll(tmp)).isZero();
        String meta = Files.readString(tmp.resolve("PRITENSESQ").resolve("metadata.json"));
        assertThat(meta).doesNotContain("generatedAt").doesNotContain("refTableColumns")
            .doesNotContain("INTEG_").doesNotContain("RDB$FOREIGN").doesNotContain("\"url\"")
            .doesNotContain("cardinality").doesNotContain("warnings")
            .contains("\"FK_PRITENSESQ_PAI\"").contains("\"triggers\"");
        String ddl = Files.readString(tmp.resolve("PRITENSESQ").resolve("ddl.sql"));
        assertThat(ddl).doesNotContain("timestamp:").doesNotContain("source:").doesNotContain("server:")
            .startsWith("-- Generated by singularidade-data-bridge\n");
        assertThat(Files.readString(tmp.resolve("_index.json"))).doesNotContain("generatedAt").doesNotContain("totalRows");
    }
}
