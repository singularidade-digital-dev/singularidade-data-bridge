package digital.singularidade.databridge.pipeline.ddl;

import org.junit.jupiter.api.Test;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class DdlScriptTest {

    @Test
    void should_drop_version_source_server_and_timestamp_from_a_stable_header() {
        String header = DdlScript.standardHeader("firebird", null, "T", "jdbc:firebirdsql://[redacted-host]/db",
            "3.0.14", List.of("CREATE TABLE"), List.of("GRANT/REVOKE"))
            + "\n-- Database default character set: NONE";
        DdlScript stable = new DdlScript(header, "CREATE TABLE \"T\" (\"A\" INTEGER);", "", List.of()).stable();
        assertThat(stable.header())
            .isEqualTo("-- Generated by singularidade-data-bridge\n"
                + "--   table:     T   driver: firebird\n"
                + "-- Included: CREATE TABLE\n"
                + "-- Skipped:  GRANT/REVOKE\n"
                + "-- Database default character set: NONE");
        assertThat(stable.body()).isEqualTo("CREATE TABLE \"T\" (\"A\" INTEGER);");
    }
}
