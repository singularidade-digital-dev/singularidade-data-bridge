package digital.singularidade.databridge.pipeline.ddl;

import digital.singularidade.databridge.source.jdbc.JdbcSource;
import digital.singularidade.databridge.support.FbFixture;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

class FirebirdDdlBuilderIT {

    private static FbFixture fx;
    private static JdbcSource src;

    @BeforeAll
    static void start() {
        fx = new FbFixture();
        src = JdbcSource.open(fx.jdbcUrl());
    }

    @AfterAll
    static void stop() {
        src.close();
        fx.close();
    }

    private static DdlScript ddl(String table) {
        return new FirebirdDdlBuilder()
            .build(src, null, table, "jdbc:firebirdsql://[redacted-host]/sgh.fdb", true).orElseThrow();
    }

    @Test
    void should_emit_shared_domains_and_sequences_first() {
        String text = ddl("PRITENSESQ").toFileText();
        assertThat(text)
            .contains("CREATE DOMAIN \"DM_FLAG\" AS CHAR(1) DEFAULT 'F' NOT NULL CHECK (VALUE IN ('T','F'));")
            .contains("CREATE DOMAIN \"DM_NOME\" AS VARCHAR(60) CHARACTER SET WIN1252 COLLATE WIN_PTBR;")
            .contains("CREATE DOMAIN \"DM_VALOR\" AS NUMERIC(15,2) DEFAULT 0 NOT NULL;")
            .contains("CREATE SEQUENCE \"GEN_IDITENSESQ\";")
            .doesNotContain("GEN_PRITENSESQ_ID");
        assertThat(text.indexOf("CREATE DOMAIN")).isLessThan(text.indexOf("CREATE TABLE"));
    }

    @Test
    void should_emit_columns_with_exact_types_domains_and_defaults() {
        String text = ddl("PRITENSESQ").toFileText();
        assertThat(text)
            .contains("    \"ID\" INTEGER NOT NULL,\n")
            .contains("    \"CODGRUPO\" INTEGER,\n")
            .contains("    \"ATIVO\" \"DM_FLAG\",\n")
            .contains("    \"VALOR\" \"DM_VALOR\",\n")
            .contains("    \"QTDE\" NUMERIC(9,3),\n")
            .contains("    \"PERC\" DECIMAL(4,2),\n")
            .contains("    \"NOME\" \"DM_NOME\",\n")
            .contains("    \"APELIDO\" VARCHAR(10) CHARACTER SET UTF8,\n")
            .contains("    \"OBS\" BLOB SUB_TYPE TEXT,\n")
            .contains("    \"FOTO\" BLOB SUB_TYPE BINARY,\n")
            .contains("    \"DTCAD\" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,\n")
            .contains("    \"TOTAL\" COMPUTED BY (VALOR * QTDE),\n")
            .contains("    \"SEQ\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n")
            .contains("    CONSTRAINT \"PK_PRITENSESQ\" PRIMARY KEY (\"ID\"),\n")
            .contains("    CONSTRAINT \"UK_PRITENSESQ_EXT\" UNIQUE (\"CODEXT\", \"EMPRESA\")\n);");
    }

    @Test
    void should_emit_indexes_in_column_order_with_direction_expression_and_state() {
        String text = ddl("PRITENSESQ").toFileText();
        assertThat(text)
            .contains("CREATE DESCENDING INDEX \"IX_PRITENSESQ_DTCAD\" ON \"PRITENSESQ\" (\"DTCAD\");")
            .contains("CREATE INDEX \"IX_PRITENSESQ_MULTI\" ON \"PRITENSESQ\" (\"NOME\", \"EMPRESA\", \"CODPAI\");")
            .contains("CREATE INDEX \"IX_PRITENSESQ_OFF\" ON \"PRITENSESQ\" (\"PERC\");\nALTER INDEX \"IX_PRITENSESQ_OFF\" INACTIVE;")
            .contains("CREATE INDEX \"IX_PRITENSESQ_UPNOME\" ON \"PRITENSESQ\" COMPUTED BY (UPPER(NOME));")
            .doesNotContain("CREATE INDEX \"FK_PRITENSESQ_PAI\"")
            .doesNotContain("RDB$FOREIGN")
            .doesNotContain("CREATE INDEX \"PK_PRITENSESQ\"");
    }

    @Test
    void should_emit_foreign_keys_and_checks_without_restrict_or_system_names() {
        String text = ddl("PRITENSESQ").toFileText();
        assertThat(text)
            .contains("ALTER TABLE \"PRITENSESQ\" ADD FOREIGN KEY (\"CODGRUPO\") REFERENCES \"TBGRUPO\" (\"CODGRUPO\");")
            .contains("ALTER TABLE \"PRITENSESQ\" ADD CONSTRAINT \"FK_PRITENSESQ_PAI\" FOREIGN KEY (\"CODPAI\", \"EMPRESA\")"
                + " REFERENCES \"TBPAI\" (\"CODIGO\", \"EMPRESA\") ON DELETE CASCADE;")
            .contains("ALTER TABLE \"PRITENSESQ\" ADD CONSTRAINT \"CK_PRITENSESQ_PERC\" CHECK (PERC BETWEEN 0 AND 100);")
            .contains("ALTER TABLE \"PRITENSESQ\" ADD CHECK (QTDE >= 0);")
            .doesNotContain("RESTRICT")
            .doesNotContain("INTEG_");
    }

    @Test
    void should_emit_comments_and_charset_header() {
        String text = ddl("PRITENSESQ").toFileText();
        assertThat(text)
            .contains("COMMENT ON TABLE \"PRITENSESQ\" IS 'Itens de esquema de prescricao';")
            .contains("COMMENT ON COLUMN \"PRITENSESQ\".\"VALOR\" IS 'Valor unitario';")
            .contains("-- Database default character set: ISO8859_1")
            .contains("singularidade-data-bridge");
    }

    @Test
    void should_emit_replayable_triggers_with_event_state_and_position() {
        String triggers = ddl("PRITENSESQ").triggersFileText();
        assertThat(triggers)
            .contains("SET TERM ^ ;")
            .contains("CREATE OR ALTER TRIGGER \"TR_PRITENSESQ_BI\" FOR \"PRITENSESQ\" ACTIVE BEFORE INSERT POSITION 0\nAS\n")
            .contains("CREATE OR ALTER TRIGGER \"TR_PRITENSESQ_BIU\" FOR \"PRITENSESQ\" INACTIVE BEFORE INSERT OR UPDATE POSITION 5\nAS\n")
            .contains("CREATE OR ALTER TRIGGER \"TR_PRITENSESQ_AD\" FOR \"PRITENSESQ\" ACTIVE AFTER DELETE POSITION 10\nAS\n")
            .contains("END^")
            .contains("SET TERM ; ^");
        assertThat(triggers.indexOf("TR_PRITENSESQ_BI\"")).isLessThan(triggers.indexOf("TR_PRITENSESQ_BIU\""));
    }

    @Test
    void should_keep_key_order_and_drop_system_constraint_names() {
        assertThat(ddl("TBPAI").toFileText())
            .contains("    CONSTRAINT \"PK_TBPAI\" PRIMARY KEY (\"CODIGO\", \"EMPRESA\")\n");
        assertThat(ddl("TBGRUPO").toFileText())
            .contains("    PRIMARY KEY (\"CODGRUPO\"),\n")
            .contains("    UNIQUE (\"CODIGOEXT\")\n")
            .doesNotContain("INTEG_")
            .doesNotContain("RDB$");
    }

    @Test
    void should_quote_mixed_case_names_and_keep_explicit_charset_none() {
        assertThat(ddl("TbMista").toFileText())
            .contains("CREATE TABLE \"TbMista\" (\n")
            .contains("    \"Cod\" INTEGER NOT NULL,\n")
            .contains("    \"Nome\" VARCHAR(20) CHARACTER SET NONE,\n")
            .contains("    PRIMARY KEY (\"Cod\")\n");
    }

    @Test
    void should_emit_unique_indexes_that_back_no_constraint() {
        assertThat(ddl("PRODUCTS").toFileText())
            .contains("    \"PRICE\" NUMERIC(10,2) NOT NULL,\n")
            .contains("CREATE UNIQUE INDEX \"UK_PRODUCTS_SKU\" ON \"PRODUCTS\" (\"SKU\");")
            .contains("CREATE INDEX \"IDX_PRODUCTS_CATEGORY\" ON \"PRODUCTS\" (\"CATEGORY\");");
    }
}
