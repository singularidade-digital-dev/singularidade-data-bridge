BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_IDITENSESQ, 1);
END^

CREATE TRIGGER TR_PRITENSESQ_BIU FOR PRITENSESQ INACTIVE BEFORE INSERT OR UPDATE POSITION 5 AS
BEGIN
  NEW.CODEXT = UPPER(NEW.CODEXT);
END^

