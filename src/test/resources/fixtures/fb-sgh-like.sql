SET SQL DIALECT 3;

CREATE DOMAIN DM_FLAG AS CHAR(1) CHARACTER SET ISO8859_1 DEFAULT 'F' NOT NULL CHECK (VALUE IN ('T','F'));
CREATE DOMAIN DM_VALOR AS NUMERIC(15,2) DEFAULT 0 NOT NULL;
CREATE DOMAIN DM_NOME AS VARCHAR(60) CHARACTER SET WIN1252 COLLATE WIN_PTBR;
COMMIT;

CREATE GENERATOR GEN_IDITENSESQ;
CREATE GENERATOR GEN_PRITENSESQ_ID;
COMMIT;

CREATE TABLE TBPAI (
  EMPRESA SMALLINT NOT NULL,
  CODIGO  INTEGER  NOT NULL,
  NOME    VARCHAR(40),
  CONSTRAINT PK_TBPAI PRIMARY KEY (CODIGO, EMPRESA)
);

CREATE TABLE TBGRUPO (
  CODGRUPO  INTEGER NOT NULL PRIMARY KEY,
  DESCR     VARCHAR(30),
  CODIGOEXT VARCHAR(10) UNIQUE
);
COMMIT;

CREATE TABLE PRITENSESQ (
  ID       INTEGER  NOT NULL,
  EMPRESA  SMALLINT NOT NULL,
  CODPAI   INTEGER  NOT NULL,
  CODGRUPO INTEGER REFERENCES TBGRUPO (CODGRUPO),
  ATIVO    DM_FLAG,
  VALOR    DM_VALOR,
  QTDE     NUMERIC(9,3),
  PERC     DECIMAL(4,2),
  NOME     DM_NOME,
  APELIDO  VARCHAR(10) CHARACTER SET UTF8,
  OBS      BLOB SUB_TYPE TEXT,
  FOTO     BLOB SUB_TYPE BINARY,
  DTCAD    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  TOTAL    COMPUTED BY (VALOR * QTDE),
  CODEXT   VARCHAR(20),
  SEQ      INTEGER GENERATED BY DEFAULT AS IDENTITY,
  CONSTRAINT PK_PRITENSESQ PRIMARY KEY (ID),
  CONSTRAINT UK_PRITENSESQ_EXT UNIQUE (CODEXT, EMPRESA),
  CONSTRAINT FK_PRITENSESQ_PAI FOREIGN KEY (CODPAI, EMPRESA) REFERENCES TBPAI (CODIGO, EMPRESA) ON DELETE CASCADE,
  CONSTRAINT CK_PRITENSESQ_PERC CHECK (PERC BETWEEN 0 AND 100),
  CHECK (QTDE >= 0)
);
COMMIT;

CREATE DESCENDING INDEX IX_PRITENSESQ_DTCAD ON PRITENSESQ (DTCAD);
CREATE INDEX IX_PRITENSESQ_UPNOME ON PRITENSESQ COMPUTED BY (UPPER(NOME));
CREATE INDEX IX_PRITENSESQ_MULTI ON PRITENSESQ (NOME, EMPRESA, CODPAI);
CREATE INDEX IX_PRITENSESQ_OFF ON PRITENSESQ (PERC);
ALTER INDEX IX_PRITENSESQ_OFF INACTIVE;
COMMIT;

COMMENT ON TABLE PRITENSESQ IS 'Itens de esquema de prescricao';
COMMENT ON COLUMN PRITENSESQ.VALOR IS 'Valor unitario';
COMMIT;

